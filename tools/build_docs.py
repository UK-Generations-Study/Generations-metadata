"""Generate the readable pages of the Generations metadata repository from its sources.

Sources (edit these)                                   Generated (do not edit)
  study-level-metadata/study.json                 ->   study-level-metadata/README.md
  ro-crate-metadata.json                          ->   resource-level-metadata/README.md
  structural-metadata/schemas/**                  ->   VERSIONS.json

Usage:
  python tools/build_docs.py           write the generated files
  python tools/build_docs.py --check   only report generated files that are out of date (exit 1 if any)
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from urllib.parse import urljoin

ROOT = Path(__file__).resolve().parent.parent
STUDY_DIR = ROOT / "study-level-metadata"
STUDY_RECORD = STUDY_DIR / "study.json"
CRATE = ROOT / "ro-crate-metadata.json"
RESOURCE_DIR = ROOT / "resource-level-metadata"
SCHEMAS = ROOT / "structural-metadata" / "schemas"
VERSIONS = ROOT / "VERSIONS.json"

NOTE = "<!-- Generated by tools/build_docs.py from {src}. Do not edit this file; edit the source and rerun. -->\n\n"
CRATE_FRAME = {"ro-crate-metadata.json", "./"}   # the crate's own header entries


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def rel(target: Path, page: Path) -> str:
    """Relative link from a generated page to a file."""
    return os.path.relpath(target, page.parent).replace(os.sep, "/")


def cell(value) -> str:
    """Make a value safe for a Markdown table cell."""
    if value is None:
        return ""
    return str(value).replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def table(head: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def as_list(value) -> list:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def ref_ids(value) -> list[str]:
    return [v["@id"] for v in as_list(value) if isinstance(v, dict) and "@id" in v]


TERM_TYPES = {"rdf:Property", "rdfs:Class"}


def is_term(entity: dict) -> bool:
    """A Generations-specific term defined inside a JSON-LD file (a property or a type)."""
    return bool(TERM_TYPES & set(as_list(entity.get("@type"))))


def term_label(t: dict) -> str:
    return t.get("rdfs:label") or str(t["@id"]).split(":")[-1].split("#")[-1]


def collect_terms() -> list[tuple[dict, str]]:
    """Every Generations-specific term defined in the repository's JSON-LD files, with the file it is in."""
    found = []
    for path in (STUDY_RECORD, CRATE):
        for e in load(path).get("@graph", []):
            if is_term(e):
                found.append((e, path.relative_to(ROOT).as_posix()))
    return found


def terms_section(entries: list[tuple[dict, str]]) -> str:
    """The one Terms section: each row carries a bookmark, so a term's full address opens its own definition."""
    out = "## Terms\n\n"
    if not entries:
        return out + "No Generations-specific terms are defined yet.\n"
    out += ("Generations-specific terms used in this repository's JSON-LD files, where "
            "[schema.org](https://schema.org) has no suitable term. Each term's definition lives in the file "
            "listed. A term's full address is this page's address followed by `#` and the term, for example "
            "`…/resource-level-metadata/README.md#populationSize`.\n\n")
    rows, seen = [], set()
    for t, src in sorted(entries, key=lambda e: term_label(e[0]).lower()):
        label = term_label(t)
        if (label, src) in seen:
            continue
        seen.add((label, src))
        rows.append([f'<a id="{label}"></a>`{label}`',
                     "type" if "rdfs:Class" in as_list(t.get("@type")) else "property",
                     t.get("rdfs:comment", ""), f"`{src}`"])
    return out + table(["Term", "Kind", "Meaning", "Defined in"], rows)


# --------------------------------------------------------------------------- schemas
class SchemaSet:
    """All JSON files under schemas/, with $ref resolution by relative path or by $id."""

    def __init__(self, folder: Path):
        self.docs: dict[Path, dict] = {}
        self.by_id: dict[str, Path] = {}
        for p in sorted(folder.rglob("*.json")):
            doc = load(p)
            self.docs[p.resolve()] = doc
            if isinstance(doc, dict) and isinstance(doc.get("$id"), str):
                self.by_id[doc["$id"].split("#")[0]] = p.resolve()

    def resolve(self, ref: str, from_path: Path):
        """Return (file, node) that `ref` points to, seen from `from_path`."""
        url, _, frag = ref.partition("#")
        if not url:
            target = from_path
        else:
            target = (from_path.parent / url).resolve()
            if target not in self.docs:
                base = self.docs[from_path].get("$id") if isinstance(self.docs[from_path], dict) else None
                target = self.by_id.get(urljoin(base, url)) if base else None
            if target is None or target not in self.docs:
                raise KeyError(f"cannot resolve $ref {ref!r} from {from_path}")
        node = self.docs[target]
        for part in [p for p in frag.split("/") if p]:
            part = part.replace("~1", "/").replace("~0", "~")
            node = node[int(part)] if isinstance(node, list) else node[part]
        return target, node

    def refs_in(self, node, path: Path, found: list):
        """Collect (ref, from_path) for every $ref inside node."""
        if isinstance(node, dict):
            if isinstance(node.get("$ref"), str):
                found.append((node["$ref"], path))
            for v in node.values():
                self.refs_in(v, path, found)
        elif isinstance(node, list):
            for v in node:
                self.refs_in(v, path, found)
        return found

    def tables(self) -> list[Path]:
        """Array-of-records schemas that no other file references (as Schema Explorer treats them)."""
        referenced = set()
        for p, doc in self.docs.items():
            for ref, src in self.refs_in(doc, p, []):
                try:
                    target, _ = self.resolve(ref.split("#")[0] + "#", src)
                except KeyError:
                    continue
                if target != src:
                    referenced.add(target)
        return [p for p, d in self.docs.items()
                if isinstance(d, dict) and d.get("type") == "array" and isinstance(d.get("items"), dict)
                and p not in referenced]


def variable_level(outputs: dict):
    ss = SchemaSet(SCHEMAS)
    versions = []
    for tp in sorted(ss.tables()):
        doc = ss.docs[tp]
        versions.append({"file": tp.relative_to(ROOT).as_posix(), "title": doc.get("title", ""),
                         "x-version": doc.get("x-version", ""), "x-dataVersion": doc.get("x-dataVersion", "")})
    outputs[VERSIONS] = json.dumps({"$comment": "Generated by tools/build_docs.py. Do not edit.",
                                    "schemas": versions}, indent=2, ensure_ascii=False) + "\n"


# --------------------------------------------------------------------------- study level
def study_level(outputs: dict):
    """Study at a glance, from study.json (JSON-LD, schema.org + Generations-specific terms)."""
    page = STUDY_DIR / "README.md"
    graph = load(STUDY_RECORD)["@graph"]
    s = next(e for e in graph if str(e.get("@id", "")).endswith("#study"))
    terms = [e for e in graph if is_term(e)]
    pub = s.get("publisher") or {}

    def period(v):
        """ISO 8601 interval ("2003-06-01/..") in words."""
        if not v or "/" not in str(v):
            return v
        start, end = str(v).split("/", 1)
        return f"From {start} (ongoing)" if end in ("", "..") else f"{start} to {end}"

    def names(v):
        return ", ".join(x.get("name", "") if isinstance(x, dict) else str(x) for x in as_list(v))

    out = [NOTE.format(src=f"[{STUDY_RECORD.name}]({STUDY_RECORD.name})"), f"# {s.get('name', 'Study')}\n\n"]
    out.append(f"Study record: [`{STUDY_RECORD.name}`]({STUDY_RECORD.name}) (JSON-LD, schema.org), "
               f"version {s.get('version', '')}, last modified {s.get('dateModified', '')}.\n\n")
    out.append(table(["", ""], [[k, v] for k, v in [
        ["Also known as", ", ".join(as_list(s.get("alternateName")))],
        ["Population size", s.get("populationSize")],
        ["Age range", s.get("typicalAgeRange")],
        ["Geographic coverage", names(s.get("spatialCoverage"))],
        ["Time covered", period(s.get("temporalCoverage"))],
        ["Follow-up", s.get("followUp")],
        ["Custodian", pub.get("name")],
        ["Data controller", names(s.get("dataController"))],
        ["Contact", (pub.get("contactPoint") or {}).get("email")],
        ["Website", s.get("url")],
        ["Keywords", ", ".join(as_list(s.get("keywords")))],
    ] if v not in (None, "")]) + "\n")
    if s.get("abstract"):
        out.append("## Summary\n\n" + s["abstract"] + "\n\n")
    if s.get("description"):
        out.append("## About the study\n\n" + s["description"] + "\n\n")
    if s.get("pathway"):
        out.append("## Coverage\n\n" + s["pathway"] + "\n\n")
    kinds = [("Sample types", s.get("materialType")), ("Data formats", s.get("encodingFormat")),
             ("Coding systems", s.get("vocabularyEncodingScheme")), ("Standards", s.get("conformsTo"))]
    kinds = [[k, ", ".join(as_list(v))] for k, v in kinds if v]
    if kinds:
        out.append("## Data types and standards\n\n" + table(["", ""], kinds) + "\n")
    links = as_list(s.get("linkableDatasets"))
    if links:
        out.append("## Linked datasets\n\n" + "".join(
            f"- [{l.get('name')}]({l.get('url')})\n" if l.get("url") else f"- {l.get('name')}\n" for l in links) + "\n")
    obs = as_list(s.get("observations"))
    if obs:
        out.append("## Key numbers\n\n" + table(["What", "Count", "As of"], [
            [o.get("description"), o.get("value"), o.get("observationDate")] for o in obs]) + "\n")
    out.append("## Access\n\n")
    if s.get("conditionsOfAccess"):
        out.append(s["conditionsOfAccess"] + "\n\n")
    out.append(table(["", ""], [[k, v] for k, v in [
        ["More information", s.get("usageInfo")],
        ["Permitted use", ", ".join(as_list(s.get("dataUseLimitation")))],
        ["Conditions", ", ".join(as_list(s.get("dataUseRequirements")))],
        ["Typical lead time", s.get("deliveryLeadTime")],
        ["Cost", s.get("accessRequestCost")],
    ] if v]) + "\n")
    if s.get("creditText"):
        out.append("## Acknowledgement\n\n" + s["creditText"] + "\n\n")
    pubs = [w for w in as_list(s.get("subjectOf")) if "ScholarlyArticle" in as_list(w.get("@type"))]
    if pubs:
        out.append("## Publications about the study\n\n" + "".join(
            f"- [{p['sameAs'].split('doi.org/')[-1]}]({p['sameAs']})\n" for p in pubs if p.get("sameAs")) + "\n")
    if terms:
        out.append("## Terms\n\nGenerations-specific terms used in `study.json` are defined in the "
                   f"[Resources overview]({rel(RESOURCE_DIR / 'README.md', page)}#terms).\n")
    outputs[page] = "".join(out).rstrip() + "\n"


# --------------------------------------------------------------------------- resource level
def resource_level(outputs: dict):
    """List every entity in the graph with its links. Makes no assumption about which types are used."""
    page = RESOURCE_DIR / "README.md"
    graph = load(CRATE)["@graph"]
    ent = {e["@id"]: e for e in graph}
    root = ent.get("./", {})
    linked_away = {i for i in ref_ids(root.get("license"))}
    items = [e for e in graph if e["@id"] not in CRATE_FRAME | linked_away and not is_term(e)]

    def label(i):
        name = ent[i].get("name", i) if i in ent else i
        if i in ent and not i.startswith("#") and "://" not in i:
            return f"[{name}]({rel(ROOT / i, page)})"
        return name

    out = [NOTE.format(src=f"[ro-crate-metadata.json]({rel(CRATE, page)})"), "# Resources overview\n\n",
           "What the Generations Study holds and how it fits together.\n\n"]
    if not items:
        out.append(root.get("description", "Placeholder. The resource graph has not been filled in yet.") + "\n")
    else:
        rows = []
        for e in items:
            links = [f"{k} → {', '.join(label(t) for t in ref_ids(v))}" for k, v in e.items()
                     if not k.startswith("@") and ref_ids(v)]
            rows.append([e["@id"].lstrip("#"), ", ".join(as_list(e.get("@type"))), label(e["@id"]),
                         e.get("description", ""), "; ".join(links)])
        out.append(table(["ID", "Type", "Name", "Description", "Links"], rows))
    out.append("\n" + terms_section(collect_terms()))
    outputs[page] = "".join(out)


# --------------------------------------------------------------------------- main
def generate() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    study_level(outputs)
    resource_level(outputs)
    variable_level(outputs)
    return outputs


def stale(outputs: dict[Path, str]) -> list[str]:
    """Generated files that are missing or different."""
    return [f"out of date: {p.relative_to(ROOT).as_posix()}" for p, text in outputs.items()
            if not p.exists() or p.read_text(encoding="utf-8") != text]


def main(argv: list[str]) -> int:
    outputs = generate()
    if "--check" in argv:
        problems = stale(outputs)
        for line in problems:
            print(line)
        print("Generated files up to date." if not problems else "Run: python tools/build_docs.py")
        return 1 if problems else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(outputs)} generated files.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
